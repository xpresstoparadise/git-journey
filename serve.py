"""Serve the Git Journey UI (web/) on 0.0.0.0:8766 — local and LAN.

    python serve.py [--port 8766] [--no-browser]
"""
from __future__ import annotations

import argparse
import functools
import http.server
import shutil
import socket
import sys
import webbrowser
from pathlib import Path

from ingest.config import FROZEN, REPO_ROOT

WEB_ROOT = REPO_ROOT / "web"


def ensure_site() -> None:
    """Standalone binary: unpack the UI next to the executable (static files are
    refreshed every run; web/data — the built film and photos — is left alone)."""
    if not FROZEN:
        return
    bundled = Path(getattr(sys, "_MEIPASS", "")) / "web"
    for src in bundled.rglob("*"):
        rel = src.relative_to(bundled)
        if rel.parts and rel.parts[0] == "data" and len(rel.parts) > 1 and not rel.name.endswith(".example.json"):
            continue
        dst = WEB_ROOT / rel
        if src.is_dir():
            dst.mkdir(parents=True, exist_ok=True)
        else:
            dst.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(src, dst)


def lan_ip() -> str:
    # UDP "connect" sends nothing; it only asks the OS which interface would route out.
    try:
        with socket.socket(socket.AF_INET, socket.SOCK_DGRAM) as s:
            s.connect(("10.255.255.255", 1))
            return s.getsockname()[0]
    except OSError:
        return "127.0.0.1"


class Handler(http.server.SimpleHTTPRequestHandler):
    extensions_map = {**http.server.SimpleHTTPRequestHandler.extensions_map, ".js": "text/javascript", ".mjs": "text/javascript"}

    def end_headers(self) -> None:
        # Data is re-generated by fetch_gitlab.py — never serve a stale copy.
        self.send_header("Cache-Control", "no-store")
        super().end_headers()

    def log_message(self, fmt: str, *args) -> None:  # quieter console
        if not str(args[1] if len(args) > 1 else "").startswith(("2", "3")):
            super().log_message(fmt, *args)


def run(host: str = "0.0.0.0", port: int = 8766, browser: bool = True) -> None:
    ensure_site()
    # Film settings from journey.json reach the page on every start — no re-fetch needed.
    from ingest.config import load_settings  # noqa: PLC0415
    from ingest.settings_file import write_ui_config  # noqa: PLC0415
    s = load_settings()
    write_ui_config(s.file, s.out_dir)
    http.server.ThreadingHTTPServer.allow_reuse_address = True
    handler = functools.partial(Handler, directory=str(WEB_ROOT))
    with http.server.ThreadingHTTPServer((host, port), handler) as httpd:
        print("Git Journey")
        print(f"  local: http://127.0.0.1:{port}/")
        if host != "127.0.0.1":
            print(f"  lan:   http://{lan_ip()}:{port}/")
        if browser:
            webbrowser.open(f"http://127.0.0.1:{port}/")
        try:
            httpd.serve_forever()
        except KeyboardInterrupt:
            pass


def main(argv: list[str] | None = None) -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--host", default="0.0.0.0")
    ap.add_argument("--lan", action="store_true", help="same as --host 0.0.0.0")
    ap.add_argument("--port", type=int, default=8766)
    ap.add_argument("--no-browser", action="store_true")
    args = ap.parse_args(argv)
    run("0.0.0.0" if args.lan else args.host, args.port, not args.no_browser)


if __name__ == "__main__":
    main()
